import itertools, time
LOG = open('sweep20/f5d.log', 'w')
def out(m):
    LOG.write(m + '\n'); LOG.flush()
T0 = time.time()
from scipy.interpolate import CubicSpline
from scipy.linalg import eig as _eig

TRUNC = 5

def pmul(a, b):
    r = {}
    for ka, va in a.items():
        for kb, vb in b.items():
            k = tuple(x+y for x, y in zip(ka, kb))
            if sum(k) > TRUNC:
                continue
            r[k] = r.get(k, 0) + va*vb
    return r
def padd(a, b):
    r = dict(a)
    for k, v in b.items():
        r[k] = r.get(k, 0) + v
    return r
def pscale(a, c):
    return {k: v*c for k, v in a.items()}
def porder(a, n):
    return {k: v for k, v in a.items() if sum(k) == n}
def conj2(a):
    return {(k[1], k[0]): np.conj(v) for k, v in a.items()}
def dz(a):
    r = {}
    for (j, k), v in a.items():
        if j > 0:
            r[(j-1, k)] = r.get((j-1, k), 0) + j*v
    return r
def dzb(a):
    r = {}
    for (j, k), v in a.items():
        if k > 0:
            r[(j, k-1)] = r.get((j, k-1), 0) + k*v
    return r
def transform(gcur, j, k, phi, lam):
    T = {(1, 0): 1.0, (j, k): phi}
    G = dict(gcur)
    for _ in range(4):
        gT = {}
        for (a2, b2), v in gcur.items():
            term = {(0, 0): v}
            for _ in range(a2):
                term = pmul(term, T)
            Tb = conj2(T)
            for _ in range(b2):
                term = pmul(term, Tb)
            for kk, vv in term.items():
                gT[kk] = gT.get(kk, 0) + vv
        Gb = conj2(G)
        r_ = padd(pscale({kk: vv for kk, vv in T.items()
                          if kk != (1, 0)}, lam), gT)
        r_ = padd(r_, pscale(pmul(
            {kk: vv for kk, vv in dz(T).items() if kk != (0, 0)},
            padd({(1, 0): lam}, G)), -1))
        r_ = padd(r_, pscale(pmul(
            dzb(T), padd({(0, 1): np.conj(lam)}, Gb)), -1))
        G = {kk: vv for kk, vv in r_.items() if sum(kk) >= 2}
    return G
def nf_sweep(g, lam):
    gnf = dict(g)
    for n2 in range(2, 6):
        for (j, k) in sorted([kk for kk in gnf if sum(kk) == n2]):
            if (j, k) in ((2, 1), (3, 2)):
                continue
            den = j*lam + k*np.conj(lam) - lam
            if abs(den) < 1e-9:
                continue
            gnf = transform(gnf, j, k, gnf[(j, k)]/den, lam)
    return gnf

def nfc12(pr):
    """c1, c2 at the operating point pr via the homological solver."""
    st = equil(pr)
    if st is None:
        return None
    A = jac(st, pr)
    ev, VL, VR = _eig(A, left=True, right=True)
    idx = [i for i in range(4) if ev[i].imag > 1e-9]
    if len(idx) < 2:
        return None
    idx.sort(key=lambda i: -ev[i].real)
    kc, ks = idx[0], idx[1]
    lam, lams = ev[kc], ev[ks]
    q = VR[:, kc]; p = VL[:, kc]
    p = p/np.vdot(q, p)
    s = VR[:, ks]; ps = VL[:, ks]
    ps = ps/np.vdot(s, ps)
    subsmap = {th_: st[0], xp_: st[1], Vdc_: st[2], xi_: st[3],
               P_: pr['P'], Q_: pr['Q'], V_: pr['V'], Xg_: pr['Xg'],
               kp_: pr['kp'], ki_: pr['ki'], kpv_: pr['kpv'],
               kiv_: pr['kiv'], C_: pr['C']}
    Dk = {}
    for k in range(2, 6):
        Dk[k] = [dict() for _ in range(4)]
        for i in range(4):
            for combo in itertools.combinations_with_replacement(
                    range(4), k):
                e = f_[i]
                for j in combo:
                    e = sp.diff(e, _x[j])
                val = complex(e.subs(subsmap).evalf())
                if abs(val) > 1e-14:
                    Dk[k][i][combo] = val
    qb, sb = np.conj(q), np.conj(s)
    U = [{(1, 0, 0, 0): q[j], (0, 1, 0, 0): qb[j],
          (0, 0, 1, 0): s[j], (0, 0, 0, 1): sb[j]} for j in range(4)]
    def mult_count(combo):
        c = 1
        for _, g2 in itertools.groupby(combo):
            c *= math.factorial(len(list(g2)))
        return c
    def pmul4(a, b):
        r = {}
        for ka, va in a.items():
            for kb, vb in b.items():
                kk = tuple(x+y for x, y in zip(ka, kb))
                if sum(kk) > TRUNC:
                    continue
                r[kk] = r.get(kk, 0) + va*vb
        return r
    P4 = [dict() for _ in range(4)]
    for k in range(2, 6):
        for i in range(4):
            for combo, val in Dk[k][i].items():
                term = {(0, 0, 0, 0): val/mult_count(combo)}
                for j in combo:
                    term = pmul4(term, U[j])
                for kk, vv in term.items():
                    P4[i][kk] = P4[i].get(kk, 0) + vv
    Gz4 = {}
    Gw4 = {}
    for i in range(4):
        for kk, vv in P4[i].items():
            Gz4[kk] = Gz4.get(kk, 0) + np.conj(p[i])*vv
            Gw4[kk] = Gw4.get(kk, 0) + np.conj(ps[i])*vv
    h = {}
    g = {}
    def compose(G4, hcur):
        hb = conj2(hcur)
        res = {}
        for (a2, b2, c2_, d2), v in G4.items():
            base = {(a2, b2): v}
            if c2_:
                hp = dict(hcur)
                for _ in range(c2_-1):
                    hp = pmul(hp, hcur)
                base = pmul(base, hp)
            if d2:
                hp = dict(hb)
                for _ in range(d2-1):
                    hp = pmul(hp, hb)
                base = pmul(base, hp)
            for kk, vv in base.items():
                res[kk] = res.get(kk, 0) + vv
        return res
    for n in range(2, 6):
        Gz2 = compose(Gz4, h)
        gn = porder(Gz2, n)
        for k, v in gn.items():
            g[k] = g.get(k, 0) + v
        if n <= 4:
            Gw2 = compose(Gw4, h)
            gb = conj2(g)
            known = padd(pmul(dz(h), padd({(1, 0): lam}, g)),
                         pmul(dzb(h), padd({(0, 1): np.conj(lam)}, gb)))
            rhs_n = porder(padd(Gw2, pscale(known, -1)), n)
            for (j, k), v in rhs_n.items():
                den = j*lam + k*np.conj(lam) - lams
                h[(j, k)] = h.get((j, k), 0) + v/den
    gnf = nf_sweep(g, lam)
    return dict(c1=gnf.get((2, 1), 0), c2=gnf.get((3, 2), 0), lam=lam)

def align(qs, ps):
    for i in range(1, len(qs)):
        c = np.vdot(qs[i-1], qs[i])
        ph = c/abs(c)
        qs[i] = qs[i]/ph
        ps[i] = ps[i]/ph
    return qs, ps

MEAS = {'mix16': 2.3619e-3, 'G1 m=0.05': 1.2409e-3,
        'Xg=0.70': 2.4158e-3, 'Q=+0.15': 3.1040e-3}
CASES = [
    dict(tag='mix16', over=dict(kp=45., ki=900., Xg=0.55), marg=0.10),
    dict(tag='G1 m=0.05', over={}, marg=0.05),
    dict(tag='Xg=0.70', over=dict(Xg=0.70), marg=0.10),
    dict(tag='Q=+0.15', over=dict(Q=0.15), marg=0.10),
]
for case in CASES:
    prb = gset('G1', **case['over'])
    Psn = 3*prb['V']**2/(4*prb['Xg'])
    def reA(P):
        q = dict(prb, P=P)
        x = equil(q)
        if x is None: return None
        cm = crit_mode(jac(x, q))
        return None if cm is None else cm.real
    grid = np.linspace(0.05, 0.985, 60)*Psn
    va = [reA(P) for P in grid]
    br = None
    for a, b, fa, fb in zip(grid[:-1], grid[1:], va[:-1], va[1:]):
        if fa is not None and fb is not None and fa < 0 <= fb:
            br = (a, b); break
    lo, hi = br
    for _ in range(45):
        m = 0.5*(lo+hi)
        v = reA(m)
        if v is None or v >= 0: hi = m
        else: lo = m
    P = margin_point(prb, 0.5*(lo+hi), case['marg'])
    pr = dict(prb, P=P)
    co0 = nf_coeffs(pr)
    st0 = co0['st']; w0 = co0['w0']
    zg = math.sqrt(co0['alpha']/co0['c1'].real)
    vlo, vhi = pr['V'] - 0.05, pr['V']
    for _ in range(30):
        vm = 0.5*(vlo+vhi)
        if equil(dict(pr, V=vm)) is None: vlo = vm
        else: vhi = vm
    AH = min(0.012, 0.85*(pr['V'] - vhi))
    Vg = pr['V'] + np.linspace(-1.05*AH, 1.05*AH, 181)
    sts, lams, c1s, qs, ps = [], [], [], [], []
    for V in Vg:
        co = nf_coeffs(dict(pr, V=V))
        sts.append(co['st']); lams.append(co['lam'])
        c1s.append(co['c1']); qs.append(co['q']); ps.append(co['p'])
    qs, ps = align(qs, ps)
    sts = np.array(sts); lams = np.array(lams); c1s = np.array(c1s)
    qs = np.array(qs); ps = np.array(ps)
    dV = Vg[1] - Vg[0]
    st_V = np.gradient(sts, dV, axis=0)
    q_V = np.gradient(qs, dV, axis=0)
    p_V = np.gradient(ps, dV, axis=0)
    n = len(Vg)
    pstV = np.array([np.vdot(ps[i], st_V[i]) for i in range(n)])
    pqV = np.array([np.vdot(ps[i], q_V[i]) for i in range(n)])
    pVqb = np.array([np.vdot(p_V[i], np.conj(qs[i])) for i in range(n)])
    g20s = np.zeros(n, complex); g11s = np.zeros(n, complex)
    g02s = np.zeros(n, complex); c3s = np.zeros(n, complex)
    Gsa = np.zeros(n, complex); Gsb = np.zeros(n, complex)
    Gs0 = np.zeros(n, complex)
    for i in range(n):
        pri = dict(pr, V=Vg[i])
        av = _avl(sts[i], pri)
        def B2c(u, v):
            return np.array([sum(_Hl[ii][j][kk](*av)*u[j]*v[kk]
                                 for j in range(4) for kk in range(4))
                             for ii in range(4)])
        qi, pi = qs[i], ps[i]
        g20s[i] = np.vdot(pi, B2c(qi, qi))
        g11s[i] = np.vdot(pi, B2c(qi, np.conj(qi)))
        g02s[i] = np.vdot(pi, B2c(np.conj(qi), np.conj(qi)))
        Ai = jac(sts[i], pri)
        w = st_V[i].astype(complex)
        Pw = w - qi*np.vdot(pi, w) - np.conj(qi)*np.vdot(np.conj(pi), w)
        y1 = np.real(np.linalg.solve(Ai, Pw))
        Gsa[i] = np.vdot(pi, B2c(y1, qi))
        Gsb[i] = np.vdot(pi, B2c(y1, np.conj(qi)))
        Gs0[i] = 0.5*np.vdot(pi, B2c(y1, y1)) + np.vdot(p_V[i], y1)
        g1d = {(2, 0): g20s[i]/2, (1, 1): g11s[i], (0, 2): g02s[i]/2}
        gnf1 = nf_sweep(g1d, lams[i])
        c3s[i] = c1s[i] - gnf1.get((2, 1), 0)
    # c2(V) on 15-point subgrid
    Vg2 = np.linspace(Vg[3], Vg[-4], 15)
    c2v = []
    okc2 = True
    for V in Vg2:
        r = nfc12(dict(pr, V=V))
        if r is None:
            okc2 = False; break
        c2v.append(r['c2'])
    if not okc2:
        out(f"{case['tag']}: c2 grid failed — skip"); continue
    c2v = np.array(c2v)
    c2sp = (CubicSpline(Vg2, c2v.real), CubicSpline(Vg2, c2v.imag))
    def c2f(V):
        V = min(max(V, Vg2[0]), Vg2[-1])
        return complex(c2sp[0](V), c2sp[1](V))
    # c5(V): c2 - quintic generated by 1D raw terms
    c5s = np.zeros(n, complex)
    for i in range(n):
        g1d = {(2, 0): g20s[i]/2, (1, 1): g11s[i], (0, 2): g02s[i]/2,
               (2, 1): c3s[i]}
        gnf1 = nf_sweep(g1d, lams[i])
        c5s[i] = c2f(Vg[i]) - gnf1.get((3, 2), 0)
    i0 = n//2
    out(f"{case['tag']}: c2(V0)={c2f(Vg[i0]):.0f} c5(V0)={c5s[i0]:.0f} "
        f"c2*zg^2/c1={abs(c2f(Vg[i0]))*zg*zg/abs(c1s[i0]):.3f} "
        f"[{time.time()-T0:.0f}s]")
    _spl = {}
    def itp(arr, V):
        key = id(arr)
        if key not in _spl:
            _spl[key] = (CubicSpline(Vg, arr.real),
                         CubicSpline(Vg, arr.imag))
        V = min(max(V, Vg[0]), Vg[-1])
        sr, si = _spl[key]
        return complex(sr(V), si(V))
    ws = w0/32
    Tt1 = 12*2*math.pi/ws
    def escape1d(a, model):
        def f(t, y):
            z = y[0] + 1j*y[1]
            zb = np.conj(z)
            V = pr['V'] - a*math.sin(ws*t)
            Vd = -a*ws*math.cos(ws*t)
            az2 = (y[0]*y[0] + y[1]*y[1])
            dz_ = (itp(lams, V)*z - itp(pstV, V)*Vd
                   - itp(pqV, V)*Vd*z + itp(pVqb, V)*Vd*zb
                   + itp(Gsa, V)*Vd*z + itp(Gsb, V)*Vd*zb
                   + itp(Gs0, V)*Vd*Vd)
            if model.startswith('A'):
                dz_ += itp(c1s, V)*az2*z
                if model == 'A5':
                    dz_ += c2f(V)*az2*az2*z
            else:
                dz_ += (0.5*itp(g20s, V)*z*z + itp(g11s, V)*z*zb
                        + 0.5*itp(g02s, V)*zb*zb
                        + itp(c3s, V)*az2*z)
                if model == 'B5':
                    dz_ += itp(c5s, V)*az2*az2*z
            return [dz_.real, dz_.imag]
        def blow(t, y):
            return math.hypot(y[0], y[1]) - 5*zg
        blow.terminal = True; blow.direction = 1
        s = solve_ivp(f, (0, Tt1), [0.0, 0.0], method='DOP853',
                      rtol=1e-10, atol=1e-14, events=blow)
        return len(s.t_events[0]) > 0
    meas = MEAS[case['tag']]
    line = f"  {case['tag']} w0/32: meas={meas:.4e}"
    for model in ('A5', 'B5'):
        alo, ahi = 1e-6, AH
        if not escape1d(ahi, model):
            line += f"  {model}:noesc"
            continue
        for _ in range(14):
            am = 0.5*(alo+ahi)
            if escape1d(am, model): ahi = am
            else: alo = am
        ap = 0.5*(alo+ahi)
        line += f"  {model}:{(ap-meas)/meas*100:+.1f}%"
    out(line + f" [{time.time()-T0:.0f}s]")
out(f"DONE wall={time.time()-T0:.0f}s")
