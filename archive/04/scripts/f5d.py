"""Quintic-extended co-moving models for the last F-GFL points.
A5 = NF form + c2(V)|z|^4 z   (c2 from the nf5 homological solver)
B5 = raw-quadratic form + c5(V)|z|^4 z, c5 = c2 - c2_quad1D where
     c2_quad1D = (3,2) coefficient generated by removing the 1D raw
     terms {g20/2, g11, g02/2, c3} (TRUNC=5 sweep) -> autonomous NF
     of B5 = (c1, c2) exactly.
Points: mix16@w0/32 (B:+1.1%), G1m0.05@w0/32 (A:-0.9% B:-2.7%),
regression checks Xg=0.70@w0/32, Q=+0.15@w0/32.
c2(V) on a 15-point subgrid, CubicSpline. Budget ~25 min.
"""
